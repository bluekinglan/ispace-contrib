export type IconName = keyof typeof SRC | 'stop' | 'close';

type Shape = { tag: string; attrs: Record<string, string> };

/** 只认稿子里出现过的那几种标签；属性名照抄，数值留成字符串交给 svg 自己解析。 */
function parse(src: string): Shape[] {
  const out: Shape[] = [];
  const tagRe = /<(path|circle|rect|line|polyline|polygon|ellipse)\s([^>]*?)\/>/g;
  for (let m = tagRe.exec(src); m; m = tagRe.exec(src)) {
    const attrs: Record<string, string> = {};
    const attrRe = /([\w-]+)="([^"]*)"/g;
    for (let a = attrRe.exec(m[2]!); a; a = attrRe.exec(m[2]!)) attrs[a[1]!] = a[2]!;
    out.push({ tag: m[1]!, attrs });
  }
  return out;
}

const cache = new Map<string, Shape[]>();
function shapes(name: keyof typeof SRC): Shape[] {
  let hit = cache.get(name);
  if (!hit) { hit = parse(SRC[name]); cache.set(name, hit); }
  return hit;
}

const COMPONENT = {
  path: Path, circle: Circle, rect: Rect, line: Line, polyline: Polyline, polygon: Polygon, ellipse: Ellipse,
} as const;

export function Icon({
  name, size = 21, color = '#292724', strokeWidth = 1.85, fill,
}: {
  name: IconName;
  size?: number;
  color?: string;
  /** 稿上默认 1.85，底栏那几颗 1.9，打勾的粗版 3。 */
  strokeWidth?: number;
  /** 实心版（点过的心）。不给就是描边。 */
  fill?: string | undefined;
}) {
  if (name === 'stop') {
    /*
      stop 是实心的：它表示「正在进行、点此停止」，描边版在小尺寸下
      看着像个空盒子，读不出「停」的意思
    */
    return (
      <Svg width={size} height={size} viewBox="0 0 24 24">
        <Rect x={7} y={7} width={10} height={10} rx={2} fill={color} />
      </Svg>
    );
  }
  const key = name === 'close' ? 'x' : name;
  return (
    <Svg width={size} height={size} viewBox="0 0 24 24" fill="none">
      {shapes(key).map((sh, i) => {
        const C = COMPONENT[sh.tag as keyof typeof COMPONENT] as React.ComponentType<Record<string, unknown>>;
        return (
          <C
            key={i}
            {...sh.attrs}
            stroke={color}
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            strokeLinejoin="round"
            fill={fill ?? 'none'}
          />
        );
      })}
    </Svg>
  );
}

