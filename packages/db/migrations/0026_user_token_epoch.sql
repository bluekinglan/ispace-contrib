-- 令牌世代号：让改密码能把已经登录的设备踢下线。
--
-- ┌─ 原先踢不掉 ───────────────────────────────────────────────────────┐
-- │ 会话是无状态 JWT，库里没有会话表，所以签出去的令牌在过期前一直有效。│
-- │ 改密码只换了 password_hash，对已经拿着 cookie 的人毫无影响——而     │
-- │ 「账号被盗了赶紧改密码」恰恰是最需要它立刻生效的场景。会话默认 30  │
-- │ 天，等它自己过期不是办法。                                         │
-- └────────────────────────────────────────────────────────────────────┘
--
-- 做法是给每个人一个世代号：签发令牌时把当时的值写进 claims，鉴权时跟库里
-- 比；改密码就 +1，于是之前签出去的全部对不上。不引入会话表的原因是 CLI 与
-- MCP 也拿这套令牌调 REST，无状态这一点要保住（见 packages/auth/src/session.ts
-- 开头那段）；一个整数能解决问题，就不必为此建表。
--
-- 默认 0 而不是 1：claims 里读不到 epoch 的旧令牌按 0 处理，正好对上这个
-- 默认值，所以这次上线不会把所有人踢下线。细节见 session.ts 里 epoch 那一项
-- 的注释。
ALTER TABLE ispace.users ADD COLUMN IF NOT EXISTS token_epoch integer NOT NULL DEFAULT 0;
