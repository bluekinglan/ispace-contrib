-- 没入围的创意也可以交作品，参与最佳人气奖。
--
-- 组织者 10.19 晚定的：初筛只取 8 个，其余人四天里照样可以把东西做出来。
-- 没入围的不路演、评委不打分、没有入围奖，只和入围作品一起参与全员投票
-- 的最佳人气奖（仍与一二三等奖互斥）。
--
-- 接口那边已经放开（交作品不再要求入围、投票名单含这些作品），这里只改
-- 页面上写着规则的四处，不然规则说一套、按钮做一套：
--   how[2]   「做出来」——开发期就是交作品的那几天
--   rules[5] 人气奖那条
--   prizes[3].how 最佳人气奖卡片上的一行小字
--   judgingNote   奖项小节底下那段说明
--
-- 照 0021 的做法按下标 jsonb_set，不整条数组重写。
UPDATE ispace.events SET
  updated_at = now(),
  config = jsonb_set(
             jsonb_set(
               jsonb_set(
                 jsonb_set(
                   config,
                   '{how,2,desc}',
                   to_jsonb('4 天开发时间，没入围也可以交作品、参与最佳人气奖。页面部署到 iSpace 专区，硬件作品传照片或视频；要用 3D 打印可以找玉龙，仅限 mini 件。'::text)
                 ),
                 '{rules,5}',
                 to_jsonb('最佳人气奖全员在 iSpace 投票，入围作品和没入围但交了作品的都参与；10.22 18:00 开放、10.23 12:00 截止，每人 2 票，不能投给自己；与一二三等奖互斥。'::text)
               ),
               '{prizes,3,how}',
               to_jsonb('京东卡 + 奖杯 · 全员投票 · 未入围也可参与'::text)
             ),
             '{judgingNote}',
             to_jsonb('路演作品全靠评委打分排名次，定一、二、三等奖；现场扫码投票只用来选最佳人气奖。最佳人气奖由全员在 iSpace 投票产生（10.22 18:00 – 10.23 12:00，每人 2 票），入围作品和没入围但交了作品的都参与，与一二三等奖互斥。全员另有两款飞书头像框。'::text)
           )
WHERE slug = '1024-2026';
