-- 1024 的下线时刻：11-01 → 10-25。
--
-- 种子里写的是 2026-11-01，那是建表时随手取的一个「足够靠后」的值。
-- 活动 10.23 当天 17:30 就结束了，照原值首页腰带还要再挂九天，10 月底
-- 点进去是一场已经办完的活动。
--
-- 10-25 零点而不是 10-23 散场那一刻：当天和第二天还有人回头看名单、找
-- 自己的作品编号、把链接转给没来的同事，腰带是他们唯一的入口。留一天缓冲，
-- 之后自动消失。
--
-- ┌─ 下线的只是腰带 ──────────────────────────────────────────────────┐
-- │ phase 到 'ended' 之后，首页那条腰带不再渲染（Banner.tsx）。        │
-- │ /1024 本身照常打开，获奖名单也还在——'ended' 在阶段序里排在        │
-- │ 'result' 之后，phaseAtLeast(phase,'result') 仍然成立。            │
-- │ 要的是「首页不再吆喝一场办完的活动」，不是「把这页删掉」。        │
-- └────────────────────────────────────────────────────────────────────┘
--
-- 改 deadlines.end 而不是把 events.phase 钉成 'ended'：钉死要有人记得在
-- 10.25 那天去点一下，而这件事没人会记得。时间到了自己切，才叫受后端控制。
UPDATE ispace.events SET
  updated_at = now(),
  config = jsonb_set(config, '{deadlines,end}', '"2026-10-25T00:00:00+08:00"')
WHERE slug = '1024-2026';
