-- 参赛规则前两条改口径，3D 打印挪进「怎么参加」。
--
-- 01 原来写「个人参赛，从想法到落地全流程由 1 人实现」——这读起来像是
-- 禁止协作，于是有人来问「两个人一起做算不算违规」。本意从来不是禁止，
-- 而是不**要求**组队：一个人也能参赛。改成直说这件事。
--
-- 02 收成一句话。原句在「方向不限，突出创新」后面挂了一串建议方向（产研
-- 提效、运营提效、硬件 + AI…），但那是**举例**不是规则：列在规则里会被当成
-- 范围看，反而显得方向有限——和这一条要说的恰好相反。
--
-- 那串举例里夹着一条不是举例的东西：3D 打印机可以找玉龙借。它是参赛者
-- 真要用的资源，删 02 时不能跟着一起丢，所以挪到 how[2]「做出来」——
-- 那一步正是 10.19–10.22 的开发期，要借设备就是在那几天。
--
-- 都用 jsonb_set 按下标改，不整条数组重写：rules 后面四条和 how 另外三步
-- 是 0019 定下的，在这里重复一遍只会让下次改的人不知道该以哪份为准。
UPDATE ispace.events SET
  updated_at = now(),
  config = jsonb_set(
             jsonb_set(
               jsonb_set(
                 config,
                 '{rules,0}',
                 to_jsonb('不强制组队，可1人参赛'::text)
               ),
               '{rules,1}',
               to_jsonb('方向不限，突出创新'::text)
             ),
             '{how,2,desc}',
             to_jsonb('4 天开发时间。页面部署到 iSpace 专区，硬件作品传照片或视频；要用 3D 打印可以找玉龙，仅限 mini 件。'::text)
           )
WHERE slug = '1024-2026';
